/** 从昵称池随机取一个；exclude 用于「换一个」时避免与当前相同 */
export async function pickNickname(random: RandomSource, exclude?: string): Promise<string> {
  const pool = NICKNAMES.filter((n) => n !== exclude);
  const b = await random.bytes(2);
  return pool[((b[0]! << 8) | b[1]!) % pool.length]!;
}
